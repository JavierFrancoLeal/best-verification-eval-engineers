def _extract_h2(body: str) -> list[str]:
    h2s: list[str] = []
    in_code = False
    for line in body.splitlines():
        if line.strip().startswith("```"):
            in_code = not in_code
            continue
        if not in_code and line.startswith("## "):
            h2s.append(line[3:].strip())
    return h2s


def _parse_frontmatter(text: str) -> tuple[dict[str, Any] | None, str]:
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", text, re.DOTALL)
    if not m:
        return None, text
    try:
        fm = yaml.safe_load(m.group(1))
    except yaml.YAMLError:
        return None, m.group(2)
    return (fm if isinstance(fm, dict) else None), m.group(2)


def _sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def check_suite_manifest(repo_root: Path) -> tuple[bool, list[str], dict[str, Any]]:
    errors: list[str] = []
    suite_path = repo_root / "suite.yaml"
    if not suite_path.is_file():
        return False, ["Missing suite.yaml at repository root"], {}
    try:
        data = yaml.safe_load(suite_path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        return False, [f"suite.yaml YAML error: {exc}"], {}
    if not isinstance(data, dict):
        return False, ["suite.yaml must parse as a YAML mapping"], {}

    ver = data.get("ecosystem_contract_version")
    if ver not in SUPPORTED_CONTRACT_VERSIONS:
        errors.append(
            f"suite.yaml: ecosystem_contract_version must be in {sorted(SUPPORTED_CONTRACT_VERSIONS)}, got {ver!r}"
        )
    if data.get("synthesis_mode") not in ALLOWED_SYNTHESIS_MODES:
        errors.append(f"suite.yaml: synthesis_mode must be in {sorted(ALLOWED_SYNTHESIS_MODES)}")
    for req in ("suite_id", "repo_name", "director_slug", "judgment_file", "schema_version"):
        if not isinstance(data.get(req), str) or not data[req].strip():
            errors.append(f"suite.yaml: missing or empty '{req}'")

    scope = data.get("sdlc_scope")
    if not isinstance(scope, dict) or not scope.get("primary_artifacts") or not scope.get("sdlc_stages"):
        errors.append("suite.yaml: sdlc_scope must declare primary_artifacts and sdlc_stages")

    tooling = data.get("tooling")
    if not isinstance(tooling, dict) or "accepted_formats" not in tooling:
        errors.append("suite.yaml: missing tooling block with accepted_formats")
    elif tooling.get("pre_scanner"):
        scanner_path = repo_root / tooling["pre_scanner"]
        if not scanner_path.is_file():
            errors.append(f"suite.yaml: tooling.pre_scanner '{tooling['pre_scanner']}' does not exist")

    targets = data.get("handoff_targets")
    if not isinstance(targets, list) or not targets:
        errors.append("suite.yaml: handoff_targets must be a non-empty list")
    else:
        for idx, t in enumerate(targets):
            if not isinstance(t, dict) or not t.get("suite_id") or not t.get("trigger_condition"):
                errors.append(f"suite.yaml: handoff_targets[{idx}] missing suite_id or trigger_condition")

    return len(errors) == 0, errors, data


def check_director_contract(repo_root: Path, suite_data: dict[str, Any]) -> tuple[bool, list[str]]:
    errors: list[str] = []
    director_slug = suite_data.get("director_slug", "")
    suite_id = suite_data.get("suite_id", "")
    director_path = repo_root / "committee" / director_slug / "SKILL.md"
    if not director_path.is_file():
        return False, [f"Missing committee/{director_slug}/SKILL.md"]

    text = director_path.read_text(encoding="utf-8")
    if len(text.splitlines()) > 500:
        errors.append(f"committee/{director_slug}/SKILL.md exceeds 500-line ceiling")

    fm, body = _parse_frontmatter(text)
    if fm is None:
        return False, [f"committee/{director_slug}/SKILL.md missing valid YAML frontmatter"]

    if fm.get("name") != director_slug:
        errors.append(f"director SKILL.md: name '{fm.get('name')}' != '{director_slug}'")
    desc = fm.get("description", "")
    if not isinstance(desc, str) or len(desc) == 0 or len(desc) > 320:
        errors.append(f"director SKILL.md: description length {len(str(desc))} invalid (must be 1..320)")
    meta = fm.get("metadata", {})
    if not isinstance(meta, dict):
        errors.append("director SKILL.md: metadata must be a mapping")
        meta = {}
    for rk in ("schema_version", "suite_id", "author"):
        if rk not in meta:
            errors.append(f"director SKILL.md: metadata missing '{rk}'")
    if meta.get("suite_id") != suite_id:
        errors.append(f"director SKILL.md: metadata.suite_id '{meta.get('suite_id')}' != '{suite_id}'")

    h2s = _extract_h2(body)
    if h2s != REQUIRED_DIRECTOR_H2:
        errors.append(f"director SKILL.md: H2 mismatch expected={REQUIRED_DIRECTOR_H2}, actual={h2s}")

    has_env_ver = any(f'envelope_version: "{v}"' in body for v in SUPPORTED_CONTRACT_VERSIONS)
    if not has_env_ver:
        errors.append(
            f"director SKILL.md: Verdict Envelope missing envelope_version in {sorted(SUPPORTED_CONTRACT_VERSIONS)}"
        )

    for tok in (
        "verdict_envelope:",
        f'suite_id: "{suite_id}"',
        "evidence_tier:",
        "evidence:",
        "visited_suites:",
        "max_hops:",
        "escalations:",
    ):
        if tok not in body:
            errors.append(f"director SKILL.md: Verdict Envelope missing '{tok}'")

    return len(errors) == 0, errors


def check_adapters_and_namespacing(repo_root: Path, suite_data: dict[str, Any]) -> tuple[bool, list[str]]:
    errors: list[str] = []
    suite_id = suite_data.get("suite_id", "")

    agents_md = repo_root / "AGENTS.md"
    if not agents_md.is_file():
        errors.append("Missing AGENTS.md")
    elif len(agents_md.read_text(encoding="utf-8")) >= 4000:
        errors.append("AGENTS.md exceeds 4,000-char limit")

    claude_md = repo_root / "CLAUDE.md"
    if not claude_md.is_symlink() or os.readlink(claude_md) != "AGENTS.md":
        errors.append("CLAUDE.md must be a relative symlink to 'AGENTS.md'")

    ag_rule = repo_root / "adapters" / "antigravity" / f"{suite_id}-bootstrap.md"
    if not ag_rule.is_file():
        errors.append(f"Missing adapters/antigravity/{suite_id}-bootstrap.md (must use exact <suite_id>- prefix)")
    elif ag_rule.stat().st_size >= 24000:
        errors.append(f"{ag_rule.name} >= 24,000 bytes limit")

    cur_rule = repo_root / "adapters" / "cursor" / f"{suite_id}-director.mdc"
    if not cur_rule.is_file():
        errors.append(f"Missing adapters/cursor/{suite_id}-director.mdc (must use exact <suite_id>- prefix)")
    else:
        ctext = cur_rule.read_text(encoding="utf-8")
        if "alwaysApply: false" not in ctext or "globs:" not in ctext:
            errors.append(f"{cur_rule.name} missing required Cursor frontmatter (alwaysApply: false, globs)")

    ws_rule = repo_root / "adapters" / "windsurf-devin" / f"{suite_id}-director.md"
    if not ws_rule.is_file():
        errors.append(f"Missing adapters/windsurf-devin/{suite_id}-director.md (must use exact <suite_id>- prefix)")
    elif len(ws_rule.read_text(encoding="utf-8")) >= 12000:
        errors.append(f"{ws_rule.name} >= 12,000-char hard limit")

    install_sh = repo_root / "adapters" / "install.sh"
    if not install_sh.is_file() or not os.access(install_sh, os.X_OK):
        errors.append("adapters/install.sh must exist and be executable (chmod +x)")

    dsh_plugin = repo_root / "adapters" / "deepseek-harness" / "dsh-plugin.json"
    if not dsh_plugin.is_file():
        errors.append("Missing adapters/deepseek-harness/dsh-plugin.json")
    else:
        try:
            json.loads(dsh_plugin.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            errors.append(f"dsh-plugin.json invalid JSON: {exc}")

    return len(errors) == 0, errors


def check_portability_and_privacy(repo_root: Path) -> tuple[bool, list[str]]:
    errors: list[str] = []
    mac_home_re = re.compile(r"/" + r"[U]sers" + r"/[A-Za-z0-9._-]+")
    win_home_re = re.compile(r"[A-Za-z]:\\" + r"[U]sers" + r"\\[A-Za-z0-9._-]+")
    hidden_session_re = re.compile(r"(?:^|[^A-Za-z0-9_-])" + r"\." + r"[d]sh/")
    email_re = re.compile(r"\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b")
    allowed_email_domains = {"example.com", "example.org", "example.net", "acme.test"}

    for path in sorted(repo_root.rglob("*")):
        if ".git" in path.parts or "__pycache__" in path.parts or ".venv" in path.parts:
            continue
        if not path.is_file() or path.is_symlink():
            continue
        rel = str(path.relative_to(repo_root))
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        for lineno, line in enumerate(text.splitlines(), start=1):
            if mac_home_re.search(line):
                errors.append(f"{rel}:{lineno}: local macOS home path detected")
            if win_home_re.search(line):
                errors.append(f"{rel}:{lineno}: local Windows home path detected")
            if hidden_session_re.search(line):
                if not (rel == ".gitignore" and line.strip() == "." + "dsh/"):
                    errors.append(f"{rel}:{lineno}: internal hidden session directory reference detected")
            for m in email_re.finditer(line):
                addr = m.group(0)
                if addr.split("@", 1)[1].lower() not in allowed_email_domains:
                    errors.append(f"{rel}:{lineno}: personal/real email address detected ({addr})")
    return len(errors) == 0, errors


def check_auditor_rules_and_citations(repo_root: Path, suite_data: dict[str, Any]) -> tuple[bool, list[str]]:
    """v1.2.0 §5.2.1: Validate declarative auditor rules.yaml files when present.

    - Strict v1.2.0 Clean-Room schema enforced whenever `clean_room_required: true` OR `schema_version == "1.2.0"`.
    - Backward-compatible universal hygiene (unique IDs, normalized/legacy-equivalent severities,
      mandatory remediation, and non-placeholder citations) enforced on legacy v1.0/v1.1 weighted_panel rulesets.
    """
    errors: list[str] = []
    suite_id = str(suite_data.get("suite_id", ""))
    auditors_root = repo_root / "committee" / "auditors"
    if not auditors_root.is_dir():
        return True, []

    rules_files = sorted(auditors_root.glob("*/rules.yaml"))
    if not rules_files:
        return True, []

    for rfile in rules_files:
        auditor_slug = rfile.parent.name
        rel = str(rfile.relative_to(repo_root))
        try:
            doc = yaml.safe_load(rfile.read_text(encoding="utf-8"))
        except yaml.YAMLError as exc:
            errors.append(f"{rel}: YAML parse error: {exc}")
            continue
        if not isinstance(doc, dict) or not isinstance(doc.get("rules"), list) or not doc["rules"]:
            errors.append(f"{rel}: must contain a non-empty 'rules' list")
            continue

        clean_room = bool(doc.get("clean_room_required", False))
        rule_schema_ver = str(doc.get("schema_version", "")).strip()
        is_legacy_weighted = (
            not clean_room
            and suite_data.get("synthesis_mode") == "weighted_panel"
            and rule_schema_ver in {"1.0.0", "1.1.0"}
        )
        strict_v12 = not is_legacy_weighted
        seen_ids: set[str] = set()

        for idx, rule in enumerate(doc["rules"]):
            prefix = f"{rel}:rules[{idx}]"
            if not isinstance(rule, dict):
                errors.append(f"{prefix}: rule entry must be a YAML mapping")
                continue

            rid = str(rule.get("id", "")).strip()
            if not rid:
                errors.append(f"{prefix}: missing non-empty 'id'")
            elif rid in seen_ids:
                errors.append(f"{prefix}: duplicate rule id '{rid}'")
            else:
                seen_ids.add(rid)

            if not str(rule.get("name", "")).strip():
                errors.append(f"{prefix}: missing non-empty 'name'")

            if not str(rule.get("mandatory_remediation", "")).strip():
                errors.append(f"{prefix}: missing non-empty 'mandatory_remediation'")

            sev = str(rule.get("severity", "")).strip()
            if not strict_v12:
                if sev not in LEGACY_EQUIVALENT_SEVERITIES:
                    errors.append(f"{prefix}: severity '{sev}' not in {sorted(LEGACY_EQUIVALENT_SEVERITIES)}")
                # Universal citation hygiene on legacy rulesets (primary_sources[] or source_id)
                ps = rule.get("primary_sources")
                src_id = str(rule.get("source_id", "")).strip()
                if isinstance(ps, list) and ps:
                    for s_idx, src in enumerate(ps):
                        if not isinstance(src, dict):
                            errors.append(f"{prefix}.primary_sources[{s_idx}]: must be a mapping")
                            continue
                        ident = str(src.get("url_or_identifier") or src.get("id") or "").strip()
                        if not ident or INVALID_SOURCE_PLACEHOLDER_RE.search(ident):
                            errors.append(f"{prefix}.primary_sources[{s_idx}]: invalid/placeholder citation '{ident}'")
                elif not src_id or INVALID_SOURCE_PLACEHOLDER_RE.search(src_id):
                    errors.append(f"{prefix}: missing valid 'primary_sources' or 'source_id'")
                continue

            # Strict v1.2.0 / Clean-Room rules.yaml schema
            cid = str(rule.get("canonical_id", "")).strip()
            expected_cid = f"{suite_id}:{auditor_slug}:{rid}" if rid else ""
            if not cid:
                errors.append(f"{prefix}: missing 'canonical_id'")
            elif expected_cid and cid != expected_cid:
                errors.append(f"{prefix}: canonical_id '{cid}' != expected '{expected_cid}'")

            if sev not in ALLOWED_SEVERITIES:
                errors.append(f"{prefix}: severity '{sev}' not in {sorted(ALLOWED_SEVERITIES)}")

            authority = next(
                (str(rule.get(k, "")).strip() for k in ("engineer_slug", "architect_slug", "authority_slug") if str(rule.get(k, "")).strip()),
                "",
            )
            if not authority:
                errors.append(f"{prefix}: missing authority slug ('engineer_slug' | 'architect_slug' | 'authority_slug')")

            if not str(rule.get("invariant_id", "")).strip():
                errors.append(f"{prefix}: missing non-empty 'invariant_id'")

            src_id = str(rule.get("source_id", "")).strip()
            if not src_id or INVALID_SOURCE_PLACEHOLDER_RE.search(src_id):
                errors.append(f"{prefix}: invalid or placeholder source_id '{src_id}' (use verified source_id or explicit UNVERIFIED_SOURCE)")

            rationale = next(
                (str(rule.get(k, "")).strip() for k in ("non_sast_rationale", "non_cpu_rationale") if str(rule.get(k, "")).strip()),
                "",
            )
            if not rationale:
                errors.append(f"{prefix}: missing 'non_sast_rationale' or 'non_cpu_rationale'")

            protocol = next(
                (
                    str(rule.get(k, "")).strip()
                    for k in ("diff_inspection_protocol", "artifact_inspection_protocol", "inspection_protocol")
                    if str(rule.get(k, "")).strip()
                ),
                "",
            )
            if not protocol:
                errors.append(f"{prefix}: missing inspection protocol ('diff_inspection_protocol' | 'artifact_inspection_protocol')")

            if not str(rule.get("false_positive_exemption", "")).strip():
                errors.append(f"{prefix}: missing non-empty 'false_positive_exemption'")

            if clean_room and rule.get("cross_model_recommended") is not True:
                errors.append(f"{prefix}: clean_room_required auditor rule must set cross_model_recommended: true")

    return len(errors) == 0, errors


def check_anti_self_auditing_integrity(repo_root: Path, suite_data: dict[str, Any]) -> tuple[bool, list[str]]:
    """v1.2.0 §8.1 & §8.2: Verify validator pin immutability and Clean-Room auditor read-only posture."""
    errors: list[str] = []

    # 1. Immutable core validator SHA-256 pin check (fail-closed: pin file is MANDATORY per §8.2)
    pin_file = repo_root / "validators" / "CORE_VALIDATOR.sha256"
    core_file = repo_root / "validators" / "ecosystem_core_validator.py"
    if not core_file.is_file():
        errors.append("Missing validators/ecosystem_core_validator.py")
    elif not pin_file.is_file():
        errors.append(
            "Missing mandatory validators/CORE_VALIDATOR.sha256 pin file (§8.2; sync via ecosystem-core/sync_core.sh)"
        )
    else:
        pin_tokens = pin_file.read_text(encoding="utf-8").strip().split()
        expected_hash = pin_tokens[0] if pin_tokens else ""
        actual_hash = _sha256_file(core_file)
        if not expected_hash or actual_hash != expected_hash:
            errors.append(
                f"Core validator drift/tamper detected: validators/ecosystem_core_validator.py sha256 "
                f"{actual_hash[:12]} != pinned {expected_hash[:12]} (re-sync via ecosystem-core/sync_core.sh)"
            )

    # 2. Clean-Room auditors MUST carry valid frontmatter and MUST NOT declare write/edit tools
    auditors_root = repo_root / "committee" / "auditors"
    if auditors_root.is_dir():
        for doc_path in sorted(list(auditors_root.glob("*/AUDITOR.md")) + list(auditors_root.glob("*/SKILL.md"))):
            rel = str(doc_path.relative_to(repo_root))
            fm, _ = _parse_frontmatter(doc_path.read_text(encoding="utf-8"))
            if fm is None:
                errors.append(f"{rel}: missing or malformed YAML frontmatter (cannot verify read-only allowed-tools)")
                continue
            allowed = fm.get("allowed-tools")
            if isinstance(allowed, str):
                tokens = [t.strip().lower() for t in re.split(r"[\s,]+", allowed) if t.strip()]
            elif isinstance(allowed, list):
                tokens = [str(t).strip().lower() for t in allowed if str(t).strip()]
            else:
                tokens = []
            bad = sorted(t for t in tokens if t in FORBIDDEN_AUDITOR_WRITE_TOOLS)
            if bad:
                errors.append(f"{rel}: Clean-Room auditor declares forbidden write/edit tools in allowed-tools: {bad}")

    return len(errors) == 0, errors


def check_multisuite_coexistence(
    repo_root: Path,
    suite_data: dict[str, Any],
    scanner_smoke_fn: Callable[[Path, Path], list[str]] | None = None,
) -> tuple[bool, list[str]]:
    """Live integration test: install suite + mock sibling suite into one workspace (100% domain-neutral)."""
    errors: list[str] = []
    suite_id = suite_data.get("suite_id", "")
    director_slug = suite_data.get("director_slug", "")
    install_sh = repo_root / "adapters" / "install.sh"
    if not install_sh.is_file():
        return False, ["Cannot run coexistence test: adapters/install.sh missing"]

    # Strictly synthetic, domain-neutral mock sibling slugs (zero hardcoded registry names)
    mock_sibling_id = "mock-sibling-suite"
    mock_sibling_dir = "mock-sibling-director"

    with tempfile.TemporaryDirectory(prefix="ecosys-coexist-") as tmp:
        dest = Path(tmp)
        (dest / "CLAUDE.md").write_text("# Existing Project CLAUDE.md\nKeep me intact.\n", encoding="utf-8")
        sib_dir = dest / ".agents" / "skills" / mock_sibling_dir
        sib_dir.mkdir(parents=True, exist_ok=True)
        (sib_dir / "SKILL.md").write_text(
            f"---\nname: {mock_sibling_dir}\ndescription: Mock sibling suite for coexistence verification.\n---\n# Mock\n",
            encoding="utf-8",
        )
        (dest / ".agents" / "rules").mkdir(parents=True, exist_ok=True)
        (dest / ".agents" / "rules" / f"{mock_sibling_id}-bootstrap.md").write_text("# Sibling rule\n", encoding="utf-8")

        proc = subprocess.run(
            ["bash", str(install_sh), "--target", "all", "--mode", "director-only", "--scope", "workspace", "--dest", str(dest)],
            capture_output=True,
            text=True,
            timeout=30,
        )
        if proc.returncode != 0:
            return False, [f"install.sh failed (rc={proc.returncode}): {proc.stderr.strip()}"]

        # 1. Sibling intact
        if not (sib_dir / "SKILL.md").is_file() or not (dest / ".agents" / "rules" / f"{mock_sibling_id}-bootstrap.md").is_file():
            errors.append("Coexistence FAIL: sibling suite files were clobbered")

        # 2. Anti-recursive-discovery: strictly 2 SKILL.md files under .agents/skills
        found_skills = sorted((dest / ".agents" / "skills").rglob("SKILL.md"))
        if len(found_skills) != 2:
            rels = [str(p.relative_to(dest)) for p in found_skills]
            errors.append(f"Coexistence FAIL: expected exactly 2 recursive SKILL.md files, found {len(found_skills)}: {rels}")

        # 3. Installed director self-contained assets
        installed_dir = dest / ".agents" / "skills" / director_slug
        if not (installed_dir / "references" / "suite.yaml").is_file():
            errors.append("Coexistence FAIL: installed director missing references/suite.yaml")
        if not (installed_dir / "dsh-plugin.json").is_file():
            errors.append("Coexistence FAIL: install_deepseek failed to install dsh-plugin.json")
        else:
            plugin_cfg = json.loads((installed_dir / "dsh-plugin.json").read_text(encoding="utf-8"))
            rel_p = plugin_cfg.get("suite_manifest")
            if rel_p and not (installed_dir / rel_p).is_file():
                errors.append(f"Coexistence FAIL: dsh-plugin.json suite_manifest='{rel_p}' does not resolve in installed dir")

        # 4. Exact <suite_id>- rules installed
        for rpath in (
            dest / ".agents" / "rules" / f"{suite_id}-bootstrap.md",
            dest / ".cursor" / "rules" / f"{suite_id}-director.mdc",
            dest / ".devin" / "rules" / f"{suite_id}-director.md",
            dest / ".windsurf" / "rules" / f"{suite_id}-director.md",
        ):
            if not rpath.is_file():
                errors.append(f"Coexistence FAIL: missing installed rule {rpath.relative_to(dest)}")

        # 5. Pre-existing regular CLAUDE.md preserved AND updated with fenced block
        claude_txt = (dest / "CLAUDE.md").read_text(encoding="utf-8")
        if "Keep me intact." not in claude_txt or f"<!-- BEGIN {suite_data.get('repo_name')} -->" not in claude_txt:
            errors.append("Coexistence FAIL: existing regular CLAUDE.md was not preserved + upserted")

        # 6. Domain-neutral CPU pre-scanner installation + CLI health check (optional domain hook via scanner_smoke_fn)
        scanner = suite_data.get("tooling", {}).get("pre_scanner")
        if scanner:
            installed_scanner = installed_dir / scanner
            if not installed_scanner.is_file():
                errors.append(f"Coexistence FAIL: installed pre_scanner missing at {installed_scanner.relative_to(dest)}")
            else:
                hproc = subprocess.run(
                    [sys.executable, str(installed_scanner), "--help"],
                    capture_output=True,
                    text=True,
                    timeout=15,
                )
                if hproc.returncode != 0:
                    errors.append(f"Coexistence FAIL: installed pre_scanner --help exited {hproc.returncode}: {hproc.stderr.strip()}")
                else:
                    # §4.4 Tier-A Scanner CLI & JSON Envelope Conformance Test (domain-neutral)
                    empty_dir = dest / "_empty_conformance_probe"
                    empty_dir.mkdir(exist_ok=True)
                    probe_json = dest / "_probe_out.json"
                    probe_sarif = dest / "_probe_out.sarif"
                    tproc = subprocess.run(
                        [
                            sys.executable,
                            str(installed_scanner),
                            "--root",
                            str(empty_dir),
                            "--json-output",
                            str(probe_json),
                            "--sarif-output",
                            str(probe_sarif),
                        ],
                        capture_output=True,
                        text=True,
                        timeout=15,
                    )
                    if tproc.returncode != 0 or not probe_json.is_file() or not probe_sarif.is_file():
                        errors.append(
                            f"Tier-A Conformance FAIL (§4.4): --root/--json-output/--sarif-output exited {tproc.returncode}: {tproc.stderr.strip()}"
                        )
                    else:
                        try:
                            pdata = json.loads(probe_json.read_text(encoding="utf-8"))
                            sdata = json.loads(probe_sarif.read_text(encoding="utf-8"))
                            missing_keys = [k for k in TIER_A_REQUIRED_JSON_KEYS if k not in pdata]
                            sk_keys = (
                                "total",
                                "oversized_count",
                                "binary_or_decode_count",
                                "os_error_count",
                                "python_syntax_error_count",
                            )
                            if missing_keys:
                                errors.append(f"Tier-A Conformance FAIL (§4.4): missing top-level JSON keys {missing_keys}")
                            elif pdata.get("suite_id") != suite_id:
                                errors.append(
                                    f"Tier-A Conformance FAIL (§4.4): suite_id={pdata.get('suite_id')!r} != {suite_id!r}"
                                )
                            elif pdata.get("evidence_tier") != "TOOL_VERIFIED":
                                errors.append(
                                    f"Tier-A Conformance FAIL (§4.4): evidence_tier={pdata.get('evidence_tier')!r} != 'TOOL_VERIFIED'"
                                )
                            elif not isinstance(pdata.get("counts"), dict) or not all(
                                k in pdata["counts"] for k in ("blocker", "major", "minor")
                            ):
                                errors.append("Tier-A Conformance FAIL (§4.4): counts must contain blocker/major/minor")
                            elif not isinstance(pdata.get("files_skipped"), dict) or not all(
                                k in pdata["files_skipped"] for k in sk_keys
                            ):
                                errors.append(f"Tier-A Conformance FAIL (§4.4): files_skipped must contain {list(sk_keys)}")
                            elif not isinstance(pdata.get("findings"), list):
                                errors.append("Tier-A Conformance FAIL (§4.4): findings must be a top-level list")
                            elif sdata.get("version") != "2.1.0":
                                errors.append(f"Tier-A Conformance FAIL (§4.4): SARIF version={sdata.get('version')!r} != '2.1.0'")
                        except Exception as exc:
                            errors.append(f"Tier-A Conformance FAIL (§4.4): invalid JSON/SARIF report ({exc})")

                    # Also verify --target / --json-out / positional --format sarif + fail-closed exit 3 on missing target
                    probe_json2 = dest / "_probe_out2.json"
                    t2proc = subprocess.run(
                        [sys.executable, str(installed_scanner), "--target", str(empty_dir), "--json-out", str(probe_json2)],
                        capture_output=True,
                        text=True,
                        timeout=15,
                    )
                    if t2proc.returncode != 0 or not probe_json2.is_file():
                        errors.append(f"Tier-A Conformance FAIL (§4.4): --target/--json-out exited {t2proc.returncode}")

                    pproc = subprocess.run(
                        [sys.executable, str(installed_scanner), str(empty_dir), "--format", "sarif"],
                        capture_output=True,
                        text=True,
                        timeout=15,
                    )
                    if pproc.returncode != 0 or not pproc.stdout.strip():
                        errors.append(
                            f"Tier-A Conformance FAIL (§4.4): positional target --format sarif exited {pproc.returncode}: {pproc.stderr.strip()}"
                        )

                    mproc = subprocess.run(
                        [sys.executable, str(installed_scanner), "--target", str(dest / "_missing_target_probe")],
                        capture_output=True,
                        text=True,
                        timeout=15,
                    )
                    if mproc.returncode != 3:
                        errors.append(
                            f"Tier-A Conformance FAIL (§4.4): missing target expected exit 3, got {mproc.returncode}"
                        )

                    if scanner_smoke_fn is not None:
                        errors.extend(scanner_smoke_fn(installed_scanner, dest))

    return len(errors) == 0, errors


def run_all_core_checks(
    repo_root: Path,
    scanner_smoke_fn: Callable[[Path, Path], list[str]] | None = None,
) -> tuple[bool, list[tuple[str, bool, list[str]]], dict[str, Any]]:
    results: list[tuple[str, bool, list[str]]] = []
    ok, errs, suite_data = check_suite_manifest(repo_root)
    results.append((f"[Core v{CORE_VALIDATOR_VERSION}] suite.yaml manifest", ok, errs))

    ok, errs = check_director_contract(repo_root, suite_data)
    results.append((f"[Core v{CORE_VALIDATOR_VERSION}] Director SKILL.md & Verdict Envelope", ok, errs))

    ok, errs = check_adapters_and_namespacing(repo_root, suite_data)
    results.append((f"[Core v{CORE_VALIDATOR_VERSION}] Nested adapters, exact <suite_id>- prefix & limits", ok, errs))

    ok, errs = check_portability_and_privacy(repo_root)
    results.append((f"[Core v{CORE_VALIDATOR_VERSION}] Portability & privacy leak gate", ok, errs))

    ok, errs = check_auditor_rules_and_citations(repo_root, suite_data)
    results.append((f"[Core v{CORE_VALIDATOR_VERSION}] Clean-Room rules.yaml schema & citation hygiene", ok, errs))

    ok, errs = check_anti_self_auditing_integrity(repo_root, suite_data)
    results.append((f"[Core v{CORE_VALIDATOR_VERSION}] Anti-self-auditing & validator SHA-256 pin", ok, errs))

    ok, errs = check_multisuite_coexistence(repo_root, suite_data, scanner_smoke_fn=scanner_smoke_fn)
    results.append((f"[Core v{CORE_VALIDATOR_VERSION}] Live multi-suite coexistence + CPU pre-scanner", ok, errs))

    all_ok = all(p for _, p, _ in results)
    return all_ok, results, suite_data


def main() -> int:
    repo_root = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent
    all_ok, results, suite_data = run_all_core_checks(repo_root)
    name = suite_data.get("repo_name", repo_root.name)
    print("=" * 76)
    print(f"  ECOSYSTEM CORE VALIDATOR v{CORE_VALIDATOR_VERSION} — {name}")
    print("=" * 76)
    for label, passed, errs in results:
        status = "PASS" if passed else "FAIL"
        print(f"  [{status}] {label}")
        for e in errs:
            print(f"         -> {e}")
    print("-" * 76)
    if all_ok:
        print(f"  ALL CORE CHECKS PASSED (v{CORE_VALIDATOR_VERSION}).")
        return 0
    print("  CORE VALIDATION FAILED.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
